# Импортируем все классы и функции из tkinter (Tk, Label, Button, Text, Frame, END и т.д.)
from tkinter import *
# Импортируем модуль messagebox под коротким именем mb для показа диалоговых окон
from tkinter import messagebox as mb
# Импортируем ttk — тематические виджеты (в данном случае нужен ttk.Scrollbar)
from tkinter import ttk
# Библиотека для выполнения HTTP-запросов к API
import requests


def load_all_rates():
    """Загружает курсы всех криптовалют к USD и выводит их в виде таблицы."""
    try:
        # Формируем URL запроса к API CoinLore:
        # start=0  — начать с первой монеты,
        # limit=100 — вернуть первые 100 монет
        url = 'https://api.coinlore.net/api/tickers/?start=0&limit=100'

        # Выполняем GET-запрос с таймаутом 10 секунд,
        # чтобы приложение не «зависло» при проблемах с сетью
        response = requests.get(url, timeout=10)

        # Если сервер вернул код ошибки (4xx, 5xx) — выбрасываем исключение
        response.raise_for_status()

        # Преобразуем ответ из JSON в словарь Python
        # и достаём список монет по ключу 'data'.
        # Если ключа нет — возвращаем пустой список (защита от неожиданного ответа)
        data = response.json().get('data', [])

        # Если список пустой — сообщаем пользователю и выходим из функции
        if not data:
            mb.showerror('Ошибка', 'Не удалось получить список валют')
            return

        # Разблокируем текстовое поле, чтобы можно было его изменить
        # (по умолчанию после первой загрузки оно в состоянии DISABLED)
        text.config(state=NORMAL)

        # Очищаем содержимое поля перед новым выводом
        # 1.0 — начало текста (строка 1, символ 0), END — конец
        text.delete(1.0, END)

        # Проходим по каждой монете из ответа API
        for coin in data:
            # Достаём символ тикера (BTC, ETH…), если нет — ставим '?'
            symbol = coin.get('symbol', '?')
            # Достаём название монеты, если нет — 'Неизвестно'
            name = coin.get('name', 'Неизвестно')
            # Достаём цену в USD и преобразуем в число с плавающей точкой
            price = float(coin.get('price_usd', 0))

            # Формируем строку таблицы с выравниванием:
            # :>6  — 6 символов с выравниванием вправо (для тикера)
            # :<25 — 25 символов с выравниванием влево (для названия)
            # :>14,.4f — 14 символов вправо, разделитель тысяч (,), 4 знака после точки
            line = f'{symbol:>6} | {name:<25} | {price:>14,.4f} USD\n'

            # Вставляем строку в конец текстового поля
            text.insert(END, line)

        # Блокируем поле обратно — теперь оно только для чтения
        text.config(state=DISABLED)

    # Обрабатываем ошибки сети (нет соединения, таймаут, HTTP-ошибки)
    except requests.exceptions.RequestException as er:
        mb.showerror('Ошибка сети', str(er))
    # Обрабатываем ошибки данных: некорректный JSON, отсутствие ключей, пустой список
    except (ValueError, KeyError, IndexError) as er:
        mb.showerror('Ошибка данных', f'Некорректный ответ API: {er}')


# Создаём главное окно приложения
root = Tk()
# Задаём заголовок окна
root.title('Курсы криптовалют к USD')
# Задаём размеры окна: ширина 560, высота 600
root.geometry('560x600')

# Заголовочная надпись в верхней части окна (жирный шрифт Arial 12)
Label(root, text='Все курсы криптовалют к USD',
      font=('Arial', 12, 'bold')).pack(pady=15)

# Создаём контейнер (Frame) для текстового поля и вертикального скроллбара.
# fill=BOTH — растягивать по обеим осям, expand=True — занимать всё свободное место
frame = Frame(root)
frame.pack(fill=BOTH, expand=True, padx=10, pady=5)

# Текстовое поле для вывода списка курсов.
# font — моноширинный шрифт, чтобы колонки выравнивались;
# wrap=NONE — не переносить длинные строки (прокрутка по горизонтали)
text = Text(frame, font=('Courier New', 10), wrap=NONE)

# Размещаем поле слева внутри frame, растягивая по обеим осям
text.pack(side=LEFT, fill=BOTH, expand=True)

# Кнопка «Обновить список», при нажатии вызывает load_all_rates
Button(text='Обновить список',
       command=load_all_rates,
       font=('Arial', 10)).pack(pady=15)

# Загружаем данные сразу при запуске приложения,
# чтобы пользователь увидел курсы без нажатия кнопки
load_all_rates()

# Запускаем главный цикл обработки событий Tkinter
# (без него окно не появится и не будет реагировать на действия)
root.mainloop()